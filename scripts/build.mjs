// Builds the shared outputs from the token files and slide templates. No dependencies.
//   node scripts/build.mjs
//   -> tokens.css             every token as a CSS custom property
//   -> slides/preview.html    all slide templates, scaled down, for a quick look
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));
const out = (p, data) => { writeFileSync(join(root, p), data); console.log("wrote", p); };

const color = read("color/tokens.json").color;
const type = read("typography/tokens.json");
const slide = read("slides/tokens.json");
const yakkety = read("yakkety-mascot/tokens.json").color.yakkety;

const px = (v) => (typeof v === "number" ? `${v}px` : v);
const lines = [];
const section = (title) => lines.push("", `  /* ${title} */`);
const prop = (name, value) => lines.push(`  --${name}: ${value};`);

section("Colour: brand, neutrals, dark surfaces, NCSSM accents (color/tokens.json)");
for (const group of ["brand", "neutral", "dark", "ncssm"]) {
  for (const [name, t] of Object.entries(color[group])) prop(`yac-${name}`, t.value);
}
for (const [name, t] of Object.entries(color.effect)) prop(`yac-${name}`, t.value);
for (const [name, t] of Object.entries(color.opacity)) prop(`yac-opacity-${name}`, t.value);

section("Yakkety mascot colours (yakkety-mascot/tokens.json)");
for (const [name, t] of Object.entries(yakkety)) prop(`yakkety-${name}`, t.value);

section("Type (typography/tokens.json)");
prop("yac-font-sans", type.font.family.sans.value);
prop("yac-font-serif", type.font.family.serif.value);
for (const [name, t] of Object.entries(type.font.weight)) prop(`yac-weight-${name}`, t.value);
for (const scale of ["slide", "web"]) {
  for (const [name, t] of Object.entries(type.type[scale])) {
    prop(`yac-${scale}-${name}-size`, px(t.size));
    prop(`yac-${scale}-${name}-weight`, t.weight);
    prop(`yac-${scale}-${name}-line-height`, t.lineHeight);
    if (t.letterSpacing && t.letterSpacing !== "0") prop(`yac-${scale}-${name}-tracking`, t.letterSpacing);
  }
}

section("Space, radius, borders (slides/tokens.json)");
for (const [name, t] of Object.entries(slide.space)) prop(`yac-space-${name}`, px(t.value));
for (const [name, t] of Object.entries(slide.radius)) prop(`yac-radius-${name}`, px(t.value));
for (const [name, t] of Object.entries(slide.border)) prop(`yac-border-${name}`, t.value);
prop("yac-slide-padding", px(slide.slide.padding.value));

out("tokens.css", `/* NCSSM YAC design tokens. Generated by scripts/build.mjs from the tokens.json files; edit those, not this. */
@import url("${type.font.family.sans.href}");

:root {${lines.join("\n")}
}
`);

// Slide template preview: each 1920 x 1080 section scaled to 480 x 270.
const dir = join(root, "slides/templates");
const files = readdirSync(dir).filter((f) => f.endsWith(".html")).sort();
const order = ["cover", "agenda", "divider", "divider-photo", "announcements", "statement", "two-column", "stat-chart", "photo-grid", "catalyst-tease", "catalyst-reveal", "closing"];
files.sort((a, b) => (order.indexOf(a.slice(0, -5)) + 1 || 99) - (order.indexOf(b.slice(0, -5)) + 1 || 99));
const tiles = files.map((f) => `<figure><div class="frame"><div class="scale">${readFileSync(join(dir, f), "utf8")}</div></div><figcaption>${f}</figcaption></figure>`).join("\n");
out("slides/preview.html", `<!doctype html>
<!-- Generated by scripts/build.mjs. Shows every file in slides/templates at quarter size. -->
<html lang="en"><head><meta charset="utf-8"><title>YAC slide templates</title>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Montserrat:ital,wght@0,400..700;1,400..700&display=swap">
<style>
body{margin:0;padding:32px;background:#e9e6df;font-family:Montserrat,Verdana,sans-serif;color:#1c2633;display:grid;grid-template-columns:repeat(auto-fill,minmax(480px,1fr));gap:32px}
figure{margin:0}figcaption{font-size:13px;font-weight:600;margin-top:8px;color:#5a6878}
.frame{width:480px;height:270px;overflow:hidden;border-radius:6px;box-shadow:0 1px 3px rgba(0,0,0,.15)}
.scale{width:1920px;height:1080px;transform:scale(.25);transform-origin:0 0}
section{position:relative;box-sizing:border-box;width:1920px;height:1080px;overflow:hidden}
section *{margin:0;box-sizing:border-box}
section aside{display:none}
section>*:not([style*="position:absolute"]){position:relative}
</style></head><body>
${tiles}
</body></html>
`);
